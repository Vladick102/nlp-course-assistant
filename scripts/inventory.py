def pdf_stats(pdf: Path) -> dict:
    doc = pymupdf.open(pdf)
    md = doc.metadata or {}
    chars = moj = lat = 0
    ext_links = 0
    xrefs: set[int] = set()
    moj_pages = 0
    for p in doc:
        t = p.get_text()
        chars += len(t.strip())
        fixed = fix_mojibake(t)
        changed = sum(a != b for a, b in zip(t, fixed, strict=False))
        moj += changed
        moj_pages += changed > 0
        lat += sum(a != b for a, b in zip(fixed, fix_latin_i(fixed), strict=False))
        ext_links += sum(1 for lk in p.get_links() if re.match(r"(https?|ftp|mailto):", lk.get("uri") or ""))
        xrefs.update(img[0] for img in p.get_images(full=True))
    n = len(doc)
    return {
        "pages": n,
        "creator": (md.get("creator") or "").strip()[:28],
        "producer": (md.get("producer") or "").strip()[:28],
        "avg_chars": round(chars / n) if n else 0,
        "ext_links": ext_links,
        "images": len(xrefs),
        "mojibake_chars": moj,
        "mojibake_pages": moj_pages,
        "latin_i": lat,
    }


def override_rows() -> list[tuple[str, str, str]]:
    """(stem, effect, rationale) from doc_overrides.yaml; rationale = the trailing/leading YAML comment."""
    data = yaml.safe_load(OVERRIDES.read_text(encoding="utf-8")) or {}
    comments: dict[str, str] = {}
    for ln in OVERRIDES.read_text(encoding="utf-8").splitlines():
        m = re.match(r'^"?([^":#]+?)"?:.*?#\s*(.*)$', ln)
        if m and not ln.startswith("#"):
            comments[m.group(1).strip()] = m.group(2).strip()
    rows = []
    for stem, o in data.items():
        eff = ", ".join(f"{k}={v}" for k, v in o.items() if k != "title") + (" + title" if "title" in o else "")
        rows.append((stem, eff.strip(", "), comments.get(stem, "")))
    return rows


def main() -> None:
    docs = registry.load()
    stats_file = path("parsed") / "ingest_stats.json"
    ing = {s["doc_id"]: s for s in json.loads(stats_file.read_text(encoding="utf-8"))} if stats_file.exists() else {}
    rows = []
    for d in docs:
        st = pdf_stats(ROOT / d.pdf_path)
        rows.append((d, st, ing.get(d.doc_id, {})))

    L: list[str] = []
    L += [
        "# Data inventory (CRISP-DM phase 2: Data Understanding)",
        "",
        "Generated by `scripts/inventory.py` from `data/parsed/documents.json`, `data/parsed/ingest_stats.json` and "
        "the raw PDFs (PyMuPDF). Raw files in `pok/`, `aks/`, `os/` are never modified; `.pptx` files are converted "
        "to PDF by LibreOffice (`data/converted/`). Hand review of every deck is in `reports/review/{pok,aks,os}.md` "
        "(written by reading sampled pages, not the full text).",
        "",
        "## 1. Corpus at a glance",
        "",
    ]
    by_type = Counter(d.doc_type for d, _, _ in rows)
    by_course = Counter(c for d, _, _ in rows for c in d.courses)
    tot = lambda k: sum(s[k] for _, s, _ in rows)  # noqa: E731
    ti = lambda k: sum(i.get(k, 0) for _, _, i in rows)  # noqa: E731
    sources = {s for d, _, _ in rows for s in d.source_files}
    L += [
        f"- **{len(rows)} indexed documents** from {len(sources)} raw files "
        f"(after de-duplication and {len(override_exclusions())} explicit exclusions); "
        f"types: {', '.join(f'{k} {v}' for k, v in sorted(by_type.items()))}.",
        f"- Documents per course (a shared deck counts for each of its courses): "
        f"{', '.join(f'{cfg()["courses"][c]["short"]} {n}' for c, n in sorted(by_course.items()))}.",
        f"- **{tot('pages')} PDF pages** → **{ti('slides')} slides** after overlay merge ({ti('merged_overlays')} "
        f"merged) and dropping empty pages ({ti('dropped_empty')}).",
        f"- {ti('needs_vision')} slides flagged `needs_vision` (figures/diagrams to describe with the VLM); "
        f"{ti('untitled')} slides without a title (genuinely untitled Beamer frames); {ti('with_links')} slides "
        f"with external links ({tot('ext_links')} link annotations in the PDFs).",
        f"- Raw-text defects measured *before* normalization: {tot('mojibake_chars')} characters of cp1251 mojibake "
        f"in {sum(1 for _, s, _ in rows if s['mojibake_chars'])} documents ({tot('mojibake_pages')} pages) and "
        f"{tot('latin_i')} Latin `i`/`I` characters used inside Ukrainian words "
        f"(in {sum(1 for _, s, _ in rows if s['latin_i'])} documents).",
        "",
        "## 2. Per-document table",
        "",
        "Columns: `chars/p` = average extractable characters per page (low ⇒ figure-heavy); `ext.links` = external "
        "URI annotations; `img` = distinct raster images; `moj.` = characters repaired by the cp1251 fix; `lat-i` = "
        "Latin-i fixes; then ingest results: slides kept, overlays merged, empty dropped, vision-flagged, untitled, "
        "slides with links.",
        "",
        "| doc_id | courses | type | pp | creator / producer | chars/p | ext.links | img | moj. | lat-i "
        "| slides | merged | empty | vision | untitled | w/links |",
        "|---|---|---|--:|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|",
    ]
    for d, s, i in rows:
        cp = f"{s['creator']} / {s['producer']}".strip(" /").replace("|", "/")
        L.append(
            f"| {d.doc_id} | {'/'.join(d.courses)} | {d.doc_type} | {s['pages']} | {cp} | {s['avg_chars']} "
            f"| {s['ext_links']} | {s['images']} | {s['mojibake_chars']} | {s['latin_i']} "
            f"| {i.get('slides', '–')} | {i.get('merged_overlays', '–')} | {i.get('dropped_empty', '–')} "
            f"| {i.get('needs_vision', '–')} | {i.get('untitled', '–')} | {i.get('with_links', '–')} |"
        )
    L += [
        f"| **total** | | | **{tot('pages')}** | | | **{tot('ext_links')}** | **{tot('images')}** "
        f"| **{tot('mojibake_chars')}** | **{tot('latin_i')}** | **{ti('slides')}** | **{ti('merged_overlays')}** "
        f"| **{ti('dropped_empty')}** | **{ti('needs_vision')}** | **{ti('untitled')}** | **{ti('with_links')}** |",
        "",
        "### Duplicate sources collapsed into one document",
        "",
        "| doc_id | parsed from | other copies |",
        "|---|---|---|",
    ]
    for d, _, _ in rows:
        if len(d.source_files) > 1:
            others = [s for s in d.source_files if s != d.pdf_path]
            L.append(f"| {d.doc_id} | `{d.pdf_path}` | {', '.join(f'`{o}`' for o in others) or '–'} |")

    L += [
        "",
        "## 3. Quirks and decisions",
        "",
        QUIRKS,
        "",
        "### 3.1 Registry overrides (`data/doc_overrides.yaml`)",
        "",
    ]
    L += ["| raw file stem | effect | why |", "|---|---|---|"]
    for stem, eff, why in override_rows():
        L.append(f"| `{stem}` | {eff} | {why or 'PDF metadata title missing or wrong; hand-written title'} |")
    L += ["", OPEN_ISSUES]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} documents)")


def override_exclusions() -> list[str]:
    data = yaml.safe_load(OVERRIDES.read_text(encoding="utf-8")) or {}
    return [k for k, v in data.items() if v.get("exclude")]


